export const DEFAULT_SITE_SETTINGS: SiteSettings = {
  id: 1,
  paybill_number: '',
  paybill_account_number: '',
  business_name: '',
  payment_instructions: 'Pay via M-Pesa using the details above, then contact us on WhatsApp with your payment confirmation.',
};

/**
 * Fetch current Site Settings (Public/Admin)
 * Returns live Supabase values or empty defaults
 */
export async function getSiteSettings(): Promise<{ data: SiteSettings; error: string | null }> {
  if (!isSupabaseConfigured() || !supabase) {
    return { data: DEFAULT_SITE_SETTINGS, error: 'SUPABASE_NOT_CONFIGURED' };
  }

  try {
    const { data, error } = await supabase
      .from('site_settings')
      .select('*')
      .order('id', { ascending: true })
      .limit(1)
      .maybeSingle();

    if (error) {
      if (isTableMissingError(error)) {
        return { data: DEFAULT_SITE_SETTINGS, error: null };
      }
      return { data: DEFAULT_SITE_SETTINGS, error: error.message };
    }

    if (!data) {
      return { data: DEFAULT_SITE_SETTINGS, error: null };
    }

    return {
      data: {
        id: data.id || 1,
        paybill_number: data.paybill_number || '',
        paybill_account_number: data.paybill_account_number || '',
        business_name: data.business_name || '',
        payment_instructions:
          data.payment_instructions ||
          DEFAULT_SITE_SETTINGS.payment_instructions,
        updated_at: data.updated_at,
      },
      error: null,
    };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to fetch site settings';
    return { data: DEFAULT_SITE_SETTINGS, error: msg };
  }
}

/**
 * Admin: Update Site Settings (Paybill, Account, Business Name, Instructions)
 */
export async function updateSiteSettings(
  settings: Partial<SiteSettings>
): Promise<{ success: boolean; data?: SiteSettings; error: string | null }> {
  if (!isSupabaseConfigured() || !supabase) {
    return { success: false, error: 'Supabase credentials are not configured.' };
  }

  try {
    const payload = {
      id: 1,
      paybill_number: settings.paybill_number ?? '',
      paybill_account_number: settings.paybill_account_number ?? '',
      business_name: settings.business_name ?? '',
      payment_instructions:
        settings.payment_instructions ??
        DEFAULT_SITE_SETTINGS.payment_instructions,
      updated_at: new Date().toISOString(),
    };

    const { data, error } = await supabase
      .from('site_settings')
      .upsert(payload, { onConflict: 'id' })
      .select()
      .single();

    if (error) {
      if (isTableMissingError(error)) {
        return {
          success: false,
          error:
            'The "site_settings" table does not exist in Supabase yet. Please run the SQL schema migration in the Security tab.',
        };
      }
      return { success: false, error: error.message };
    }

    return { success: true, data: data as SiteSettings, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to update site settings';
    return { success: false, error: msg };
  }
}

