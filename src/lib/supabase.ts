/**
 * Admin: Insert a new vehicle into the database
 */
export async function insertVehicle(
  vehicle: Omit<Vehicle, 'id' | 'created_at'>
): Promise<{ success: boolean; data?: Vehicle; error: string | null }> {
  if (!isSupabaseConfigured() || !supabase) {
    return { success: false, error: 'Supabase is not configured' };
  }

  try {
    const payload = {
      make: vehicle.make.trim(),
      model: vehicle.model.trim(),
      year: Number(vehicle.year),
      mileage: vehicle.mileage ? String(vehicle.mileage).trim() : '',
      transmission: vehicle.transmission || 'Automatic',
      fuel_type: vehicle.fuel_type || 'Petrol',
      body_type: vehicle.body_type || 'SUV',
      condition: vehicle.condition || 'Foreign Used',
      price: Number(vehicle.price),
      discount_price:
        vehicle.discount_price !== null &&
        vehicle.discount_price !== undefined &&
        Number(vehicle.discount_price) > 0
          ? Number(vehicle.discount_price)
          : null,
      status: vehicle.status || 'available',
      is_featured: Boolean(vehicle.is_featured),
      description: vehicle.description || '',
      photos: Array.isArray(vehicle.photos) ? vehicle.photos : [],
    };

    const { data, error } = await supabase
      .from('vehicles')
      .insert([payload])
      .select()
      .single();

    if (error) {
      console.error('Error inserting vehicle:', error);
      return { success: false, error: error.message };
    }

    const created: Vehicle = {
      ...data,
      photos: Array.isArray(data.photos) ? data.photos : [],
      price: Number(data.price) || 0,
      discount_price: data.discount_price ? Number(data.discount_price) : null,
      is_featured: Boolean(data.is_featured),
    };

    return { success: true, data: created, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to insert vehicle';
    return { success: false, error: msg };
  }
}

/**
 * Admin: Update an existing vehicle
 */
export async function updateVehicle(
  id: string | number,
  vehicle: Partial<Omit<Vehicle, 'id' | 'created_at'>>
): Promise<{ success: boolean; data?: Vehicle; error: string | null }> {
  if (!isSupabaseConfigured() || !supabase) {
    return { success: false, error: 'Supabase is not configured' };
  }

  try {
    const payload: Record<string, any> = {};
    if (vehicle.make !== undefined) payload.make = vehicle.make.trim();
    if (vehicle.model !== undefined) payload.model = vehicle.model.trim();
    if (vehicle.year !== undefined) payload.year = Number(vehicle.year);
    if (vehicle.mileage !== undefined) {
      payload.mileage = vehicle.mileage ? String(vehicle.mileage).trim() : '';
    }
    if (vehicle.transmission !== undefined) payload.transmission = vehicle.transmission;
    if (vehicle.fuel_type !== undefined) payload.fuel_type = vehicle.fuel_type;
    if (vehicle.body_type !== undefined) payload.body_type = vehicle.body_type;
    if (vehicle.condition !== undefined) payload.condition = vehicle.condition;
    if (vehicle.price !== undefined) payload.price = Number(vehicle.price);
    if (vehicle.discount_price !== undefined) {
      payload.discount_price =
        vehicle.discount_price !== null && Number(vehicle.discount_price) > 0
          ? Number(vehicle.discount_price)
          : null;
    }
    if (vehicle.status !== undefined) payload.status = vehicle.status;
    if (vehicle.is_featured !== undefined) payload.is_featured = Boolean(vehicle.is_featured);
    if (vehicle.description !== undefined) payload.description = vehicle.description;
    if (vehicle.photos !== undefined) payload.photos = vehicle.photos;

    const { data, error } = await supabase
      .from('vehicles')
      .update(payload)
      .eq('id', id)
      .select()
      .single();

    if (error) {
      console.error(`Error updating vehicle ${id}:`, error);
      return { success: false, error: error.message };
    }

    const updated: Vehicle = {
      ...data,
      photos: Array.isArray(data.photos) ? data.photos : [],
      price: Number(data.price) || 0,
      discount_price: data.discount_price ? Number(data.discount_price) : null,
      is_featured: Boolean(data.is_featured),
    };

    return { success: true, data: updated, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Failed to update vehicle';
    return { success: false, error: msg };
  }
}

