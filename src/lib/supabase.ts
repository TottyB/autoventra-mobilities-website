/**
 * Fetch all vehicles from Supabase
 */
export async function getVehicles(): Promise<GetVehiclesResult> {
  if (!isSupabaseConfigured() || !supabase) {
    return { data: [], error: 'SUPABASE_NOT_CONFIGURED' };
  }

  try {
    const { data, error } = await supabase
      .from('vehicles')
      .select('*')
      .order('created_at', { ascending: false });

    if (error) {
      if (isTableMissingError(error)) {
        console.warn(
          'Supabase connected, but "vehicles" table is not created yet. Please execute the database schema migration.'
        );
        return { data: [], error: 'TABLE_NOT_FOUND', tableMissing: true };
      }
      console.warn('Notice while querying Supabase vehicles:', error.message);
      return { data: [], error: error.message };
    }

    const normalized: Vehicle[] = (data || []).map((v) => ({
      ...v,
      photos: Array.isArray(v.photos) ? v.photos : [],
      price: Number(v.price) || 0,
      discount_price:
        v.discount_price !== null && v.discount_price !== undefined
          ? Number(v.discount_price)
          : null,
      is_featured: Boolean(v.is_featured),
    }));

    return { data: normalized, error: null, tableMissing: false };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Unknown database error';
    return { data: [], error: msg };
  }
}

