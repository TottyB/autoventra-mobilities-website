export const isSupabaseConfigured = (): boolean => {
  return Boolean(
    supabaseUrl &&
      supabaseAnonKey &&
      supabaseUrl !== 'MY_SUPABASE_URL' &&
      supabaseAnonKey !== 'MY_SUPABASE_ANON_KEY' &&
      supabaseUrl.startsWith('http')
  );
};

